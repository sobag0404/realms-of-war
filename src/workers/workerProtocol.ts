/**
 * Shared protocol/types for Web Worker communication.
 *
 * All messages between the main thread and workers use these types.
 * Workers are self-contained and cannot import from the main bundle,
 * so they re-declare the message types they need inline. This file
 * exists for the main thread to have a single source of truth.
 *
 * Every request and response includes a `requestId` so that the
 * WorkerManager can match responses to the correct pending promise,
 * even when multiple concurrent requests of the same type are in
 * flight.
 */

// ─── Pathfinding Worker ────────────────────────────────────────────────────

export interface PathfindingRequest {
  type: 'findPath';
  /** Unique identifier for this request, echoed in the response. */
  requestId: string;
  /** Map tiles indexed by "q,r" key with terrain info. */
  tiles: Record<string, { terrain: string }>;
  /** Starting hex. */
  from: { q: number; r: number };
  /** Destination hex. */
  to: { q: number; r: number };
  /** Available movement points. */
  movementPoints: number;
}

export interface PathfindingResponse {
  type: 'findPathResult';
  /** Echoed from the original request for correct response routing. */
  requestId: string;
  /** Shortest path from `from` to `to` (null if unreachable). */
  path: Array<{ q: number; r: number }> | null;
  /** All hexes reachable within `movementPoints`. */
  reachable: Array<{ q: number; r: number }>;
}

// ─── AI Worker ────────────────────────────────────────────────────────────

export interface AiRequest {
  type: 'generateTurn';
  /** Unique identifier for this request, echoed in the response. */
  requestId: string;
  /** Serialized GameState (plain object). */
  state: unknown;
  /** AI player generating commands. */
  playerId: string;
  /** Difficulty level affecting decision quality. */
  difficulty: string;
}

export interface AiResponse {
  type: 'generateTurnResult';
  /** Echoed from the original request for correct response routing. */
  requestId: string;
  /** Serialized GameCommand[] generated by the AI. */
  commands: unknown[];
}

// ─── MapGen Worker ────────────────────────────────────────────────────────

export interface MapGenRequest {
  type: 'generateMap';
  /** Unique identifier for this request, echoed in the response. */
  requestId: string;
  /** Map width in hexes. */
  width: number;
  /** Map height in hexes. */
  height: number;
  /** Random seed for deterministic generation. */
  seed: number;
  /** Number of players to place. */
  playerCount: number;
}

export interface MapGenResponse {
  type: 'generateMapResult';
  /** Echoed from the original request for correct response routing. */
  requestId: string;
  /** Serialized MapData (plain object). */
  mapData: unknown;
  /** Starting hex positions for each player. */
  startingPositions: Array<{ q: number; r: number }>;
}

// ─── Simulation Worker ───────────────────────────────────────────────────

export interface SimulationRequest {
  type: 'simulate';
  /** Unique identifier for this request, echoed in the response. */
  requestId: string;
  /** Serialized GameState. */
  state: unknown;
  /** Serialized GameCommand[] to apply. */
  commands: unknown[];
}

export interface SimulationResponse {
  type: 'simulateResult';
  /** Echoed from the original request for correct response routing. */
  requestId: string;
  /** Final state after applying all commands. */
  finalState: unknown;
  /** Events generated during simulation. */
  events: unknown[];
}

// ─── Error Response ──────────────────────────────────────────────────────

export interface WorkerErrorResponse {
  type: 'error';
  /** Echoed from the original request for correct response routing. */
  requestId: string;
  /** Original request type that caused the error. */
  requestType: string;
  /** Error message. */
  message: string;
}

// ─── Union types ──────────────────────────────────────────────────────────

export type WorkerRequest =
  | PathfindingRequest
  | AiRequest
  | MapGenRequest
  | SimulationRequest;

export type WorkerResponse =
  | PathfindingResponse
  | AiResponse
  | MapGenResponse
  | SimulationResponse
  | WorkerErrorResponse;
